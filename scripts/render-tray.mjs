// Renders tray icon frames for every theme from its character.svg and
// writes src-tauri/src/tray_frames.rs (include_bytes! table + theme list).
//   macOS:   themes/<id>/tray/out/mac/{awake-N,asleep}.png   (36 px, drawn at 18 pt)
//   Windows: themes/<id>/tray/out/win/<16|20|24|32>/...       (per DPI)
import { Resvg } from "@resvg/resvg-js";
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const TIP_PULSE = ["#ff7a1a", "#ff8f2a", "#ffb23a", "#ffe14a", "#ffb23a", "#ff8f2a"];
const SIZES = { mac: [36], win: [16, 20, 24, 32] };

const themes = fs.readdirSync(path.join(ROOT, "themes"))
  .filter((d) => fs.existsSync(path.join(ROOT, "themes", d, "theme.json")))
  .map((d) => JSON.parse(fs.readFileSync(path.join(ROOT, "themes", d, "theme.json"), "utf8")))
  .sort((a, b) => (a.order ?? 99) - (b.order ?? 99));

/** Remove the element with this id, balancing nested <g> tags. */
function drop(svg, id) {
  const t = svg.indexOf(`<text id="${id}"`);
  if (t >= 0) return svg.slice(0, t) + svg.slice(svg.indexOf("</text>", t) + 7);
  const start = svg.indexOf(`<g id="${id}"`);
  if (start < 0) return svg;
  let depth = 0;
  const re = /<g[\s>]|<\/g>/g;
  re.lastIndex = start;
  for (let m; (m = re.exec(svg)); ) {
    depth += m[0] === "</g>" ? -1 : 1;
    if (depth === 0) return svg.slice(0, start) + svg.slice(m.index + 4);
  }
  throw new Error(`unbalanced <g id="${id}">`);
}

function frame(base, theme, { tip, wisp, asleep }) {
  let s = base;
  for (const id of ["wisps", "puffs", "zzz"]) s = drop(s, id);
  s = s.replace(/(<circle id="tip"[^>]*fill=")[^"]*"/, `$1${tip}"`);
  if (asleep) s = s.replace('<g id="lids" opacity="0">', '<g id="lids">');
  if (wisp) {
    const [, cx, cy] = s.match(/<circle id="tip" cx="([\d.]+)" cy="([\d.]+)"/);
    const extra = `<circle cx="${+cx + 2}" cy="${+cy - 10 - wisp.dy}" r="${6 + wisp.dy / 6}" fill="#c4c4cf" stroke="none" opacity="${wisp.o}"/>`;
    s = s.replace(/<\/svg>\s*$/, `${extra}</svg>`);
  }
  return s.replace(/viewBox="[^"]*"/, `viewBox="${theme.tray.viewBox}"`).replace(/ width="\d+" height="\d+"/, "");
}

const rs = ["// @generated by scripts/render-tray.mjs — do not edit.", ""];
rs.push("pub const THEMES: &[(&str, &str)] = &[");
for (const t of themes) rs.push(`    (${JSON.stringify(t.id)}, ${JSON.stringify(t.name)}),`);
rs.push("];", "", "pub struct Frames { pub awake: &'static [&'static [u8]], pub asleep: &'static [u8] }", "");
rs.push("/// (theme id, platform, size px) -> frames", "pub fn table() -> &'static [(&'static str, &'static str, u32, Frames)] {", "    &[");

for (const t of themes) {
  const base = fs.readFileSync(path.join(ROOT, "themes", t.id, "character.svg"), "utf8");
  const frames = [];
  for (let i = 0; i < t.tray.awakeFrames; i++) {
    frames.push(frame(base, t, { tip: TIP_PULSE[i % TIP_PULSE.length], wisp: { dy: i * 6, o: (1 - i / t.tray.awakeFrames).toFixed(2) } }));
  }
  const asleep = frame(base, t, { tip: "#8a8a8a", asleep: true });
  for (const [plat, sizes] of Object.entries(SIZES)) {
    for (const px of sizes) {
      const dir = path.join(ROOT, "themes", t.id, "tray", "out", plat, plat === "mac" ? "" : String(px));
      fs.mkdirSync(dir, { recursive: true });
      const write = (name, svg) => fs.writeFileSync(path.join(dir, name),
        new Resvg(svg, { fitTo: { mode: "height", value: px } }).render().asPng());
      frames.forEach((svg, i) => write(`awake-${i}.png`, svg));
      write("asleep.png", asleep);
      const rel = (n) => `../../themes/${t.id}/tray/out/${plat}${plat === "mac" ? "" : "/" + px}/${n}`;
      rs.push(`        (${JSON.stringify(t.id)}, "${plat}", ${px}, Frames {`);
      rs.push(`            awake: &[${frames.map((_, i) => `include_bytes!("${rel(`awake-${i}.png`)}")`).join(", ")}],`);
      rs.push(`            asleep: include_bytes!("${rel("asleep.png")}"),`, "        }),");
    }
  }
}
rs.push("    ]", "}", "");
fs.writeFileSync(path.join(ROOT, "src-tauri", "src", "tray_frames.rs"), rs.join("\n"));
console.log(`rendered ${themes.length} themes`);
